// Generates lib/projects.ts from the images in public/proyectos/<slug>/.
// Run after adding/removing project images:  node scripts/gen-projects.mjs
import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DIR = join(ROOT, "public/proyectos");

const EXCLUDE_SLUGS = new Set(["valle"]); // empty folder
const EXCLUDE_FILES = new Set([
  "despacho-de-arquitectura-en-monterrey-Restaurante-Crispy-Pollo.jpg", // low-res OG thumb
]);

const NAMES = {
  "terraza-pangea": "Terraza Pangea",
  kampai: "Kampai",
  "cafe-laurel": "Café Laurel",
  nailz: "Nailz",
  "ludoteca-valle-alto": "Ludoteca Valle Alto",
  "valle-alto-club-de-golf": "Valle Alto Club de Golf",
  "crispy-pollo": "Crispy Pollo",
  "e-80": "E-80",
  "edificio-vh": "Edificio VH",
  "oficinas-majadma": "Oficinas MAJADMA",
  "tp-zentralia": "TP Zentralia",
  "valle-alto-club-de-golf-gimnasio": "Valle Alto Gimnasio",
};

// Chosen cover per project (portrait where available, else best square/landscape).
const COVERS = {
  "terraza-pangea": "EA_AES_SRPA_24_005AV2_5310_P-scaled-1.webp",
  kampai: "anta-arquitectura-comercial-kampai-1-scaled.webp",
  "cafe-laurel": "anta-arquitectura-comercial-cafe-laurel-1.webp",
  nailz: "anta-arquitectura-comercial-nailz-2.webp",
  "ludoteca-valle-alto": "arquitectura-corporativo-ludoteca-7.webp",
  "valle-alto-club-de-golf": "anta-arquitectura-corporativo-valle-alto-areas-comunes-2.webp",
  "crispy-pollo": "anta-arquitectura-comercial-crispy-pollo-1.webp",
  "e-80": "arquitectura-corporativo-e80-2.webp",
  "edificio-vh": "anta-arquitectura-corporativo-edificio-vh-1.webp",
  "oficinas-majadma": "EA_AES_SOMA_23_003AV2_3480_P.webp",
  "tp-zentralia": "arquitectura-corporativo-tp-zentralia-2.webp",
  "valle-alto-club-de-golf-gimnasio": "valle-alto-gimnasio.webp",
};

const FEATURED = new Set([
  "terraza-pangea",
  "kampai",
  "cafe-laurel",
  "nailz",
  "ludoteca-valle-alto",
  "valle-alto-club-de-golf",
]);

// Display / route order: featured first, then the rest.
const ORDER = [
  "terraza-pangea",
  "kampai",
  "cafe-laurel",
  "nailz",
  "ludoteca-valle-alto",
  "valle-alto-club-de-golf",
  "crispy-pollo",
  "e-80",
  "edificio-vh",
  "oficinas-majadma",
  "tp-zentralia",
  "valle-alto-club-de-golf-gimnasio",
];

const IMG_RE = /\.(webp|jpe?g|png)$/i;
const naturalSort = (a, b) => a.localeCompare(b, undefined, { numeric: true, sensitivity: "base" });
const ident = (slug, i) => "img_" + slug.replace(/[^a-z0-9]/gi, "_") + "_" + i;

const imports = [];
const objects = [];

for (const slug of ORDER) {
  if (EXCLUDE_SLUGS.has(slug)) continue;
  const files = readdirSync(join(DIR, slug))
    .filter((f) => IMG_RE.test(f) && !EXCLUDE_FILES.has(f))
    .sort(naturalSort);
  if (files.length === 0) throw new Error(`no images for ${slug}`);
  const cover = COVERS[slug];
  if (!cover || !files.includes(cover)) throw new Error(`cover missing for ${slug}: ${cover}`);

  const varOf = {};
  files.forEach((f, i) => {
    const v = ident(slug, i);
    varOf[f] = v;
    imports.push(`import ${v} from "@/public/proyectos/${slug}/${f}";`);
  });
  const gallery = files.filter((f) => f !== cover).map((f) => varOf[f]);

  objects.push(
    `  {
    slug: ${JSON.stringify(slug)},
    nombre: ${JSON.stringify(NAMES[slug])},
    categoria: null,
    featured: ${FEATURED.has(slug)},
    cover: ${varOf[cover]},
    galeria: [${gallery.join(", ")}],
  }`,
  );
}

const out = `// AUTO-GENERATED by scripts/gen-projects.mjs — do not edit by hand.
// Regenerate after changing project images: node scripts/gen-projects.mjs
import type { StaticImageData } from "next/image";

${imports.join("\n")}

export type Categoria = "comercial" | "corporativo" | "residencial";

export interface Project {
  slug: string;
  nombre: string;
  /** Pendiente de categorizar (se asignará después). */
  categoria: Categoria | null;
  featured: boolean;
  cover: StaticImageData;
  galeria: StaticImageData[];
}

export const projects: Project[] = [
${objects.join(",\n")},
];

export const featuredProjects = projects.filter((p) => p.featured);

export function getProject(slug: string): Project | undefined {
  return projects.find((p) => p.slug === slug);
}

/** The next project in order (wraps around) — for the "siguiente proyecto" link. */
export function getNextProject(slug: string): Project {
  const i = projects.findIndex((p) => p.slug === slug);
  return projects[(i + 1) % projects.length];
}
`;

writeFileSync(join(ROOT, "lib/projects.ts"), out);
console.log(`wrote lib/projects.ts — ${objects.length} projects, ${imports.length} imports`);
